export type TranslationKey = keyof typeof dictionaries.en

export function resolveLanguage(value?: string): LanguageCode {
  return value === 'hi' || value === 'es' ? value : 'en'
}

export function localeForLanguage(value?: string): string {
  const language = resolveLanguage(value)
  return language === 'hi' ? 'hi-IN' : language === 'es' ? 'es-ES' : 'en-IN'
}

export function translate(value: string | undefined, key: TranslationKey, variables: Record<string, string | number> = {}): string {
  const language = resolveLanguage(value)
  return Object.entries(variables).reduce(
    (copy, [name, replacement]) => copy.replaceAll(`{${name}}`, String(replacement)),
    dictionaries[language][key] as string,
  )
}
